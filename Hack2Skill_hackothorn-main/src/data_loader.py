"""Data loading and caching module for REDROB Recruit Intelligence.

Guarantees:
- Safe, read-only loading from disk.
- Candidate IDs preserved as strings.
- Rank parsed as integer, score as float.
- Uses st.cache_data for instant sub-second retrieval without recalculating ranking.
- Graceful fallbacks for missing optional profile fields.
"""

from __future__ import annotations

import csv
import json
import os
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import pandas as pd
import streamlit as st

from src.preparation import find_project_root, prepare_top_100_artifacts


def get_default_paths() -> Dict[str, Path]:
    """Resolve standard data and output paths."""
    root = find_project_root()
    return {
        "root": root,
        "ranked_csv": root / "output" / "ranked_candidates.csv",
        "alt_ranked_csv": root / "data" / "top_100_candidates.csv",
        "breakdown_csv": root / "output" / "ranked_candidates_breakdown.csv",
        "ranked_json": root / "output" / "ranked_candidates.json",
        "top_100_profiles": root / "output" / "top_100_profiles.json",
        "manifest": root / "output" / "top_100_manifest.json",
        "job_description": root / "data" / "job_description.txt",
        "alt_job_description": root / "config" / "job_description.txt",
        "transparency_dir": root / "transparency",
    }


def get_file_mtime_hash(file_path: Path) -> str:
    """Return mtime string as cache invalidation key."""
    if not file_path.exists():
        return "missing"
    return f"{file_path.stat().st_mtime}_{file_path.stat().st_size}"


@st.cache_data(show_spinner=False)
def load_ranked_csv(csv_path_str: Optional[str] = None) -> Tuple[pd.DataFrame, str]:
    """Load and parse the verified ranked candidates CSV.

    Preserves candidate_id as string, rank as int, score as float.
    Returns (DataFrame, source_path_str).
    """
    paths = get_default_paths()
    if csv_path_str:
        path = Path(csv_path_str)
        if not path.exists():
            raise FileNotFoundError(f"Ranked candidate CSV not found at: {path}")
    else:
        path = paths["ranked_csv"]
        if not path.exists():
            if paths["alt_ranked_csv"].exists():
                path = paths["alt_ranked_csv"]
            else:
                raise FileNotFoundError(f"Ranked candidate CSV not found at: {path}")

    # Read CSV enforcing string for candidate_id
    df = pd.read_csv(
        path,
        dtype={"candidate_id": str, "rank": int, "score": float, "reasoning": str},
        keep_default_na=False,
    )

    # Normalize columns
    df.columns = [c.strip().lower() for c in df.columns]
    return df, str(path)


@st.cache_data(show_spinner=False)
def load_all_candidates_data() -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    """Load the complete top-100 unified records and audit manifest.

    Reads from the disk-persisted `top_100_profiles.json`. If missing,
    automatically runs a fast one-time extraction and caches the result.
    """
    paths = get_default_paths()
    profiles_path = paths["top_100_profiles"]
    manifest_path = paths["manifest"]

    if not profiles_path.exists() or not manifest_path.exists():
        # Run preparation once
        prepare_top_100_artifacts(base_dir=paths["root"], force_refresh=False)

    candidates: List[Dict[str, Any]] = []
    manifest: Dict[str, Any] = {}

    if profiles_path.exists():
        with open(profiles_path, "r", encoding="utf-8") as f:
            candidates = json.load(f)

    if manifest_path.exists():
        with open(manifest_path, "r", encoding="utf-8") as f:
            manifest = json.load(f)

    # If profiles JSON was missing, fallback to CSV with minimal fields
    if not candidates:
        df, _ = load_ranked_csv()
        for _, row in df.iterrows():
            candidates.append({
                "candidate_id": str(row["candidate_id"]),
                "rank": int(row["rank"]),
                "score": float(row["score"]),
                "reasoning": str(row["reasoning"]),
                "candidate_domain": "ai_ml",
                "years_of_experience": 0.0,
                "current_title": "Not available in loaded data",
                "current_company": "Not available in loaded data",
                "skills": [],
                "career_history": [],
                "education": [],
            })

    return candidates, manifest


@st.cache_data(show_spinner=False)
def load_transparency_reports() -> Dict[str, Any]:
    """Load audit and transparency reports generated by the pipeline."""
    paths = get_default_paths()
    trans_dir = paths["transparency_dir"]
    reports: Dict[str, Any] = {}

    report_files = [
        "ranking_report.json",
        "quality_report.json",
        "cleaning_report.json",
        "transformation_report.json",
        "validation_report.json",
    ]

    for fname in report_files:
        fpath = trans_dir / fname
        if fpath.exists():
            try:
                with open(fpath, "r", encoding="utf-8") as f:
                    reports[fname.replace(".json", "")] = json.load(f)
            except Exception:
                reports[fname.replace(".json", "")] = {}
        else:
            reports[fname.replace(".json", "")] = {}

    return reports


@st.cache_data(show_spinner=False)
def load_job_description() -> str:
    """Load target job description text."""
    paths = get_default_paths()
    jd_path = paths["job_description"]
    if not jd_path.exists() and paths["alt_job_description"].exists():
        jd_path = paths["alt_job_description"]

    if jd_path.exists():
        with open(jd_path, "r", encoding="utf-8") as f:
            return f.read()
    return "Job description text not available in repository."
